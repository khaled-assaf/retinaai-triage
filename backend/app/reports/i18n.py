def normalize_lang(lang: str | None) -> str:
    lang = (lang or "").lower().split("-")[0]
    return lang if lang in LANGUAGES else DEFAULT_LANGUAGE


def t(lang: str, key: str):
    """Look up a string, falling back to English."""
    return T.get(lang, {}).get(key, T[DEFAULT_LANGUAGE][key])


def fmt_date(lang: str, iso_value: str | None) -> str:
    if not iso_value:
        return t(lang, "none")
    from datetime import datetime

    dt = datetime.fromisoformat(iso_value.replace("Z", "+00:00"))
    return dt.strftime(DATE_FORMATS.get(lang, DATE_FORMATS["en"]))


def fmt_datetime(lang: str, iso_value: str | None) -> str:
    if not iso_value:
        return t(lang, "none")
    from datetime import datetime

    dt = datetime.fromisoformat(iso_value.replace("Z", "+00:00"))
    return dt.strftime(DATE_FORMATS.get(lang, DATE_FORMATS["en"]) + " %H:%M UTC")


def reminder_text(lang: str, name: str | None, followup_type: str, due_date: str) -> str:
    return t(lang, "reminder").format(
        name=name or "",
        type=t(lang, "followup_types").get(followup_type, followup_type),
        date=fmt_date(lang, due_date),
    ).replace(" ,", ",").replace("  ", " ")
